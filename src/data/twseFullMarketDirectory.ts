/**
 * 快速搜尋上市櫃股票 (支援 4 碼代號前綴、中文模糊搜尋、拼音匹配)
 */
export function searchTaiwanMarketStocks(query: string, maxResults = 12): MarketStockItem[] {
  const q = query.trim().toUpperCase().replace(/-?TW$/i, '').replace(/[^0-9A-Z\u4e00-\u9fa5]/g, '');
  if (!q) return [];

  const results: MarketStockItem[] = [];

  for (const item of TWSE_FULL_MARKET_STOCKS) {
    if (item.code.startsWith(q) || item.name.includes(q) || item.industry.includes(q)) {
      results.push(item);
      if (results.length >= maxResults) break;
    }
  }

  return results;
}
